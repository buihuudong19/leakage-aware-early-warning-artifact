"""LaTeX macros for the checks added during revision.

usage: python tools/gen_extra_tex.py EXTRA_DIR OUT_TEX

Reads the tables of tools/recal_cap_check.py and, when present, those of tools/rq2_chronology_check.py,
tools/policy_timing_check.py and tools/summarise_extra.py (seed check and sample check).
"""
import sys
from pathlib import Path

import pandas as pd

if len(sys.argv) != 3:
    sys.exit(__doc__)
EX, OUT = Path(sys.argv[1]) / "tables", Path(sys.argv[2])
lines = ["%% generated by tools/gen_extra_tex.py from the tables of tools/recal_cap_check.py and tools/summarise_extra.py"]


def m(name, val, note=""):
    lines.append(f"\\newcommand{{\\{name}}}{{{val}}}" + (f"  % {note}" if note else ""))


def num(x, d=1):
    if pd.isna(x):
        raise ValueError("missing value")
    s = f"{x:.{d}f}"
    if float(s) == 0:
        return f"{0:.{d}f}"
    return f"${s}$" if s.startswith("-") else s


S = pd.read_csv(EX / "recal_cap_check_summary.csv")
W = pd.read_csv(EX / "recal_cap_check_windows.csv")
g = lambda mod, strat, met: float(S[(S.model == mod) & (S.strategy == strat) & (S.metric == met)]["mean"].iloc[0])
# logistic regression is deterministic, so its numbers equal those of the reported run on any platform; XGBoost
# numbers depend on the platform's random-number generator (see tools/recal_cap_check.py) and are not used in the text
shift = g("lr", "cap20_age4 - cap20", "citl_diff")
m("XAgeFourShift", f"{100 * abs(shift):.1f}", "LR: change of calibration-in-the-large (points) when orders younger than 4 days are dropped")
m("XAgeFourShiftMax", f"{100 * max(abs(g(mm, 'cap20_age4 - cap20', 'citl_diff')) for mm in ('lr', 'xgb')):.1f}",
  "both learners: largest change of calibration-in-the-large (points) when orders younger than 4 days are dropped")
m("XNoCapMaxW", f"{W[W.strategy == 'nocap_age4'].max_weight.max():.0f}", "largest uncapped weight of an order at least 4 days old")
nocap = abs(g("lr", "nocap_age4", "citl_diff") - g("lr", "cap20_age4", "citl_diff"))
m("XNoCapDiff", f"{100 * nocap:.2f}", "change of calibration-in-the-large (points) when the cap is removed for orders of 4 days or more")
for mm, L in (("xgb", "Xgb"), ("lr", "Lr")):
    m(f"XCapHundredCitl{L}", num(100 * g(mm, "cap100", "citl_diff")), "cap 100, calibration-in-the-large (points)")
    m(f"XCapHundredInter{L}", num(g(mm, "cap100", "cal_intercept"), 2), "cap 100, calibration intercept")
    m(f"XCapTwentyCitl{L}", num(100 * g(mm, "cap20", "citl_diff")), "cap 20 refitted in the same run")
    m(f"XSpeedSlow{L}", num(100 * g(mm, "speed", "citl_delivered_within_7d_no")), "weights by predicted transit, slow deliveries")
    m(f"XSpeedFast{L}", num(100 * g(mm, "speed", "citl_delivered_within_7d_yes")), "weights by predicted transit, fast deliveries")
    m(f"XTwentySlow{L}", num(100 * g(mm, "cap20", "citl_delivered_within_7d_no")), "cap 20, slow deliveries")
    m(f"XTwentyFast{L}", num(100 * g(mm, "cap20", "citl_delivered_within_7d_yes")), "cap 20, fast deliveries")

# seed check (XGBoost, refitted seeds; the reported run is not counted)
if (EX / "seed_check_by_seed.csv").is_file():
    B = pd.read_csv(EX / "seed_check_by_seed.csv", dtype={"seed": str})
    B = B[B["seed"] != "reported"]
    q = lambda name: B.loc[B.quantity == name, "value"]
    lines.append("%% seed check: XGBoost refitted with the selected configurations and other seeds")
    if len(q("rq3_cal_intercept_ipw_minus_platt")):
        m("XSeedRqThreeN", str(len(q("rq3_cal_intercept_ipw_minus_platt"))), "seeds in the RQ3/RQ4 seed check")
        d = -q("rq3_cal_intercept_ipw_minus_platt")          # positive when weighting lowers the intercept
        m("XSeedIcptRedLo", num(d.min(), 2)); m("XSeedIcptRedHi", num(d.max(), 2), "reduction of the calibration intercept by weighting")
        c = 100 * q("rq3_citl_diff_ipw")
        m("XSeedCitlIpwLo", num(c.min())); m("XSeedCitlIpwHi", num(c.max()), "calibration-in-the-large after weighting (points)")
        c = 100 * q("rq3_citl_diff_platt")
        m("XSeedCitlPlattLo", num(c.min())); m("XSeedCitlPlattHi", num(c.max()), "calibration-in-the-large, rolling Platt (points)")
        for r in ("5", "10"):
            v = 100 * q(f"rq3_saving_r{r}_ipw_minus_platt")
            L = {"5": "Five", "10": "Ten"}[r]
            m(f"XSeedSav{L}Lo", num(v.min())); m(f"XSeedSav{L}Hi", num(v.max()), f"saving, weighted - rolling Platt, r = {r} (points)")
    if len(q("rq2_ec_t0")):
        m("XSeedRqTwoN", str(len(q("rq2_ec_t0"))), "seeds in the RQ2 seed check")
        gaps = pd.concat([q(f"rq2_ec_t0_minus_{x}") for x in ("purchase", "approval", "delivery")])
        m("XSeedDECMin", num(100 * gaps.min()), "smallest lead of hand-over over purchase, approval and delivery (points)")
        ec = 100 * q("rq2_ec_t0")
        m("XSeedECtZeroLo", f"{ec.min():.1f}"); m("XSeedECtZeroHi", f"{ec.max():.1f}", "early catch rate at hand-over (%)")
        m("XSeedTzeroBestN", str(int(q("rq2_t0_highest").sum())), "seeds in which hand-over has the highest early catch rate")

# sample check (RQ1)
if (EX / "sample_check_summary.csv").is_file():
    T = pd.read_csv(EX / "sample_check_summary.csv").set_index("variant")
    lines.append("%% sample check (RQ1)")
    tag = {"main": "Main", "undelivered": "Undel", "unreviewed0": "Unrev", "both": "Both"}
    for v, L in tag.items():
        if v not in T.index:
            continue
        r = T.loc[v]
        if "n" in T.columns and pd.notna(r["n"]):
            m(f"XSamp{L}N", f"{int(r['n']):,}".replace(",", "{,}"), f"{v}: orders in the sample")
        for mm, M in (("lr", "Lr"), ("xgb", "Xgb")):
            m(f"XSamp{L}InflP{M}", f"{r[f'infl_P_{mm}_pct']:.0f}\\%", f"{v}: inflation by post-hand-over features")
            m(f"XSamp{L}InflAll{M}", f"{r[f'infl_R+G+P_{mm}_pct']:.0f}\\%", f"{v}: inflation by all shortcuts")
        for sc, S_ in (("none", "Ref"), ("R", "R")):
            m(f"XSamp{L}XL{S_}", num(r[f"xgb_minus_lr_{sc}"], 3), f"{v}: XGBoost - LR PR-AUC, {sc}")
            m(f"XSamp{L}XL{S_}CI", f"{num(r[f'xgb_minus_lr_{sc}_lo'], 3)} to {num(r[f'xgb_minus_lr_{sc}_hi'], 3)}")

# ranges over the sample variants (all except main), for Table 10
if (EX / "sample_check_summary.csv").is_file() and (EX / "sample_check_rq24.csv").is_file():
    T = pd.read_csv(EX / "sample_check_summary.csv")
    T = T[T.variant != "main"]
    Q = pd.read_csv(EX / "sample_check_rq24.csv")
    Q = Q[~Q.variant.isin(["main", "reported"])]
    if len(T) and len(Q):
        lines.append("%% ranges over the sample variants undelivered, unreviewed0 and both")
        infl = T[[c for c in T.columns if c.startswith("infl_")]].to_numpy()
        m("XSampInflLo", f"{infl.min():.0f}\\%"); m("XSampInflHi", f"{infl.max():.0f}\\%", "inflation by P or by all shortcuts, both learners")
        for key, L in (("infl_P_", "P"), ("infl_R+G+P_", "All")):
            v = T[[c for c in T.columns if c.startswith(key)]].to_numpy()
            m(f"XSampInfl{L}Lo", f"{v.min():.0f}\\%"); m(f"XSampInfl{L}Hi", f"{v.max():.0f}\\%", f"inflation, {key[5:-1]}, both learners")
        rev = ((T.xgb_minus_lr_none_hi < 0) & (T.xgb_minus_lr_R_lo > 0)).all()
        m("XSampReversalWord", "every" if rev else "not every", "variants in which XGBoost - LR is negative (reference) and positive (random split), intervals excluding zero")
        q = lambda name: Q.loc[Q.quantity == name, "value"]
        m("XSampTzeroBestWord", "every" if (q("rq2_t0_highest") == 1).all() else "not every", "variants and learners with hand-over best")
        gaps = pd.concat([q(f"rq2_ec_t0_minus_{x}") for x in ("purchase", "approval", "delivery")])
        m("XSampDECMinAll", num(100 * gaps.min()), "smallest lead of hand-over over purchase, approval, delivery (pp), all variants and learners")
        d = -q("rq3_cal_intercept_ipw_minus_platt")
        m("XSampIcptRedMin", num(d.min(), 2)); m("XSampIcptRedMax", num(d.max(), 2), "intercept reduction by weighting, all variants and learners")

# RQ2 with strictly valid chronology (tools/rq2_chronology_check.py)
if (EX / "rq2_chronology_summary.csv").is_file():
    C = pd.read_csv(EX / "rq2_chronology_summary.csv")
    lines.append("%% RQ2 on the orders whose training labels all precede their scoring time")
    m("XChronDropOrders", f"{100 * (1 - C.share_orders_kept.iloc[0]):.1f}\\%", "orders dropped from the cohorts")
    m("XChronDropPos", f"{100 * (1 - C.share_low_rated_kept.iloc[0]):.1f}\\%", "low-rated orders dropped")
    e = C[C.milestone.isin(["purchase", "approval", "delivery"])]
    m("XChronLeadMin", num(100 * e.t0_minus.min()), "smallest lead of hand-over over purchase, approval, delivery (pp)")
    m("XChronLeadMax", num(100 * e.t0_minus.max()))
    m("XChronCIWord", "all" if (e.t0_minus_lo > 0).all() else "not all", "intervals of these leads above zero")
    best = all(C[(C.model == mm)].set_index("milestone").early_catch.idxmax() == "t0" for mm in C.model.unique())
    m("XChronTzeroBest", "yes" if best else "no", "hand-over has the highest early catch rate for both learners")

# timing of the daily alert policy (tools/policy_timing_check.py)
if (EX / "policy_timing_summary.csv").is_file():
    T = pd.read_csv(EX / "policy_timing_summary.csv").set_index("model")
    lines.append("%% timing of the daily policy: end-of-day batch, online rule, equal volume")
    m("XEodPos", str(int(T.all_pos_answered_same_day.iloc[0])), "low-rated orders answered before the end of the hand-over day")
    m("XEodPosN", f"{int(T.all_pos.iloc[0]):,}".replace(",", "{,}"), "low-rated orders in the evaluation windows")
    m("XEodTpMax", str(int(T.all_topk_tp_answered_same_day.max())), "daily-rule true positives answered the same day")
    for mm, L in (("xgb", "Xgb"), ("lr", "Lr")):
        r = T.loc[mm]
        m(f"XOnlinePrec{L}", f"{r.online_precision:.2f}"); m(f"XOnlineRec{L}", f"{r.online_recall:.2f}")
        m(f"XOnlineCv{L}", f"{r.online_cv:.2f}", "online rule: threshold = 90th percentile of the past 7 days")
        m(f"XOnlineShare{L}", f"{100 * r.online_share:.1f}\\%")
    dd = max(abs(T.topk_precision - T.eqvol_precision).max(), abs(T.topk_recall - T.eqvol_recall).max())
    m("XEqVolMaxDiff", f"{100 * dd:.1f}", "largest change of precision or recall, daily rule vs equal-volume threshold (pp)")

# RQ2 and RQ3/RQ4 under other sample conditions (tools/sample_variants.py, tools/summarise_extra.py)
if (EX / "sample_check_rq24.csv").is_file():
    Q = pd.read_csv(EX / "sample_check_rq24.csv")
    lines.append("%% RQ2 and RQ3/RQ4 under other sample conditions (configurations of the reported run)")
    tag = {"undelivered": "Undel", "unreviewed0": "Unrev", "both": "Both"}
    for v, L in tag.items():
        g = Q[Q.variant == v]
        if g.empty:
            continue
        qq = lambda name: g.loc[g.quantity == name, "value"]
        if len(qq("rq2_t0_highest")):
            m(f"XSamp{L}TzeroBest", "yes" if (qq("rq2_t0_highest") == 1).all() else "no", f"{v}: hand-over best for both learners")
            m(f"XSamp{L}EarlyBest", "yes" if (qq("rq2_t0_or_3d_highest") == 1).all() else "no",
              f"{v}: hand-over or three days later best for both learners")
            gaps = pd.concat([qq(f"rq2_ec_t0_minus_{x}") for x in ("purchase", "approval", "delivery")])
            m(f"XSamp{L}DECMin", num(100 * gaps.min()), f"{v}: smallest lead of hand-over over purchase, approval, delivery (pp)")
        if len(qq("rq3_cal_intercept_ipw_minus_platt")):
            d = -qq("rq3_cal_intercept_ipw_minus_platt")
            m(f"XSamp{L}IcptRedLo", num(d.min(), 2)); m(f"XSamp{L}IcptRedHi", num(d.max(), 2), f"{v}: intercept reduction, both learners")
            c = 100 * qq("rq3_citl_diff_ipw")
            m(f"XSamp{L}CitlIpwLo", num(c.min())); m(f"XSamp{L}CitlIpwHi", num(c.max()), f"{v}: CITL after weighting (points)")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
